def get_test_knowledge(canonical_name: str) -> Optional[Dict[str, Any]]:
    """Retrieves reviewed clinical background for a supported biomarker."""
    return LAB_KNOWLEDGE_BASE.get(canonical_name)

def explain_test_purpose(
    canonical_name: str,
    printed_reason: Optional[str] = None,
    patient_reason: Optional[str] = None
) -> Dict[str, str]:
    """
    Carefully distinguishes:
    1. Reason printed on requisition/report (if present)
    2. Reason volunteered by patient (if present)
    3. General medical purpose of the test
    """
    knowledge = get_test_knowledge(canonical_name)
    general_purpose = knowledge["why_ordered"] if knowledge else "Commonly checked as part of routine health screening."

    actual_reason = None
    if printed_reason and printed_reason.strip():
        actual_reason = f"Documented on report: '{printed_reason.strip()}'"
    elif patient_reason and patient_reason.strip():
        actual_reason = f"You shared that you were testing for: '{patient_reason.strip()}'"
    else:
        actual_reason = "Specific clinical reason for ordering this test was not noted on the report."

    return {
        "general_purpose": general_purpose,
        "actual_reason_status": actual_reason,
        "knowledge_version": KNOWLEDGE_VERSION
    }
